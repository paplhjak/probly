"""Hand-checked tests for the DDU decomposition.

The fixture has 4 points and ``K=3``. Expected ``A_hat`` / ``E_hat``
values were generated by running the closed-form formulae through
``numpy``/``math.log`` and locking the resulting ``repr()`` strings
in this file. A regression in the formulae or in the wrapper will
fail one of these to ``atol=1e-6``.

Decomposition under test (Mukhoti et al. 2023):

    cross_entropy:
        A_hat = -sum_k probs[k] log probs[k]            (entropy in nats)
        H_hat = probs                                    (soft (N, K))
    zero_one:
        A_hat = 1 - max_k probs[k]
        H_hat = argmax_k probs[k]                        (hard (N,) int64)
    E_hat = -density                                     (negate so HIGHER -> MORE OOD)
"""

from __future__ import annotations

import numpy as np
import pytest

from probly.quantification.decomposition import (
    OutputSchema,
    ddu_decomposition,
    decompose_from_schema,
)

# ---------------------------------------------------------------------------
# Fixture: 4 points, K=3.
#
#   i=0  probs=[0.7, 0.2, 0.1]      density=-2.0  (in-distribution-ish)
#   i=1  probs=[1/3, 1/3, 1/3]      density=-10.0 (OOD-est by density)
#   i=2  probs=[0.9, 0.05, 0.05]    density=-1.5  (most in-distribution)
#   i=3  probs=[0.4, 0.3, 0.3]      density=-5.0
# ---------------------------------------------------------------------------

_PROBS = np.array(
    [
        [0.7, 0.2, 0.1],
        [1.0 / 3.0, 1.0 / 3.0, 1.0 / 3.0],
        [0.9, 0.05, 0.05],
        [0.4, 0.3, 0.3],
    ],
    dtype=np.float64,
)
_DENSITY = np.array([-2.0, -10.0, -1.5, -5.0], dtype=np.float64)

_EXPECTED_E_HAT = np.array([2.0, 10.0, 1.5, 5.0], dtype=np.float32)

# Cross-entropy A_hat values, locked from `numpy`'s computation.
_EXPECTED_A_HAT_CE = np.array(
    [
        0.8018185525433372,  # -(0.7 ln 0.7 + 0.2 ln 0.2 + 0.1 ln 0.1)
        1.0986122886681096,  # ln(3)
        0.39439769144744274,  # -(0.9 ln 0.9 + 2 * 0.05 ln 0.05)
        1.0888999753452238,  # -(0.4 ln 0.4 + 2 * 0.3 ln 0.3)
    ],
    dtype=np.float64,
)

_EXPECTED_A_HAT_ZO = np.array(
    [
        1.0 - 0.7,
        1.0 - 1.0 / 3.0,
        1.0 - 0.9,
        1.0 - 0.4,
    ],
    dtype=np.float64,
)
_EXPECTED_H_HAT_ZO = np.array([0, 0, 0, 0], dtype=np.int64)
_EXPECTED_H_HAT_CE = _PROBS.astype(np.float32)


# ---------------------------------------------------------------------------
# Direct-call tests
# ---------------------------------------------------------------------------


def test_ddu_cross_entropy_matches_locked_values() -> None:
    out = ddu_decomposition(_PROBS, _DENSITY, "cross_entropy")
    assert out["A_hat"].dtype == np.float32
    assert out["E_hat"].dtype == np.float32
    assert out["H_hat"].dtype == np.float32
    assert out["A_hat"].shape == (4,)
    assert out["E_hat"].shape == (4,)
    assert out["H_hat"].shape == (4, 3)
    np.testing.assert_allclose(out["A_hat"], _EXPECTED_A_HAT_CE, atol=1e-6)
    np.testing.assert_allclose(out["E_hat"], _EXPECTED_E_HAT, atol=1e-6)
    np.testing.assert_allclose(out["H_hat"], _EXPECTED_H_HAT_CE, atol=1e-6)


def test_ddu_zero_one_matches_locked_values() -> None:
    out = ddu_decomposition(_PROBS, _DENSITY, "zero_one")
    assert out["A_hat"].dtype == np.float32
    assert out["E_hat"].dtype == np.float32
    assert out["H_hat"].dtype == np.int64
    assert out["A_hat"].shape == (4,)
    assert out["E_hat"].shape == (4,)
    assert out["H_hat"].shape == (4,)
    np.testing.assert_allclose(out["A_hat"], _EXPECTED_A_HAT_ZO, atol=1e-6)
    np.testing.assert_allclose(out["E_hat"], _EXPECTED_E_HAT, atol=1e-6)
    np.testing.assert_array_equal(out["H_hat"], _EXPECTED_H_HAT_ZO)


def test_ddu_e_hat_is_monotone_in_ood() -> None:
    """The OOD-est point (lowest density) gets the highest E_hat."""
    out = ddu_decomposition(_PROBS, _DENSITY, "cross_entropy")
    # i=1 has density -10 (most OOD); E_hat[1] should be the largest.
    assert out["E_hat"].argmax() == 1
    # i=2 has density -1.5 (most in-distribution); E_hat[2] should be smallest.
    assert out["E_hat"].argmin() == 2


