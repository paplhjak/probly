def test_dispatcher_routes_ddu_cross_entropy() -> None:
    out_direct = ddu_decomposition(_PROBS, _DENSITY, "cross_entropy")
    out_dispatch = decompose_from_schema(
        {"probs": _PROBS, "density": _DENSITY},
        "cross_entropy",
        np.arange(3, dtype=np.float64),
        schema="ddu_probs_density",
    )
    np.testing.assert_array_equal(out_dispatch["A_hat"], out_direct["A_hat"])
    np.testing.assert_array_equal(out_dispatch["E_hat"], out_direct["E_hat"])
    np.testing.assert_array_equal(out_dispatch["H_hat"], out_direct["H_hat"])


def test_dispatcher_routes_ddu_zero_one() -> None:
    out_direct = ddu_decomposition(_PROBS, _DENSITY, "zero_one")
    out_dispatch = decompose_from_schema(
        {"probs": _PROBS, "density": _DENSITY},
        "zero_one",
        np.arange(3, dtype=np.float64),
        schema="ddu_probs_density",
    )
    np.testing.assert_array_equal(out_dispatch["A_hat"], out_direct["A_hat"])
    np.testing.assert_array_equal(out_dispatch["E_hat"], out_direct["E_hat"])
    np.testing.assert_array_equal(out_dispatch["H_hat"], out_direct["H_hat"])


def test_dispatcher_ddu_missing_keys_raises() -> None:
    with pytest.raises(ValueError, match=r"probs.*density"):
        decompose_from_schema(
            {"probs": _PROBS},  # missing 'density'
            "cross_entropy",
            np.arange(3, dtype=np.float64),
            schema="ddu_probs_density",
        )


def test_dispatcher_unknown_schema_raises() -> None:
    with pytest.raises(ValueError, match="unknown output_schema"):
        decompose_from_schema(
            {"foo": np.zeros((4, 3))},
            "cross_entropy",
            np.arange(3, dtype=np.float64),
            schema="not_a_real_schema",  # type: ignore[arg-type]
        )


def test_output_schema_alias_lists_ddu() -> None:
    """Sanity check: `ddu_probs_density` is in the locked schema set."""
    assert "ddu_probs_density" in OutputSchema.__args__  # type: ignore[attr-defined]
